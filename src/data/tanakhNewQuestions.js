// ───────────── מי קשור לציטוט ─────────────
const QUOTE_BANK = [
  'יוסף', 'צפורה', 'אהוד בן גרא', 'עשיו', 'בנימין', 'יוכבד',
  'אברהם', 'אפרים ומנשה', 'יעקב', 'פרעה', 'נדב ואביהוא', 'שמואל',
]

function quoteQuestion(quote, answer, index) {
  const answerIndex = QUOTE_BANK.indexOf(answer)
  const distractors = []
  let step = 3 + (index % 3)
  let cursor = answerIndex
  while (distractors.length < 3) {
    cursor = (cursor + step) % QUOTE_BANK.length
    const candidate = QUOTE_BANK[cursor]
    if (candidate !== answer && !distractors.includes(candidate)) distractors.push(candidate)
    else step = 1
  }
  const options = [...distractors]
  options.splice((index * 2) % 4, 0, answer)
  return mc(L.quoteLink, `מי קשור לציטוט: ${quote}?`, options, answer)
}

