const counters = {}

function nextId(level) {
  const key = Object.keys(GI_NEW_LEVELS).find(item => GI_NEW_LEVELS[item] === level)
  counters[level] = (counters[level] || 0) + 1
  return `gi-new-${key}-${counters[level]}`
}

function base(level, extra) {
  return {
    id: nextId(level),
    grade: 'grade-8',
    subject: GI_NEW_SUBJECT,
    level,
    activityType: 'practice',
    ...extra,
  }
}

function mc(level, text, options, answer, explanation) {
  return base(level, {
    type: 'multiple',
    text,
    options,
    correct_answer: [answer],
    ...(explanation ? { explanation } : {}),
  })
}

function open(level, text, answers, explanation) {
  return base(level, {
    type: 'open',
    text,
    options: [],
    correct_answer: Array.isArray(answers) ? answers : [answers],
    ...(explanation ? { explanation } : {}),
  })
}

// pool: מאגר פריטים מקובלים (חלופות עם |); minItems: כמה פריטים נדרשים מהתלמיד
function list(level, text, pool, minItems, explanation) {
  return base(level, {
    type: 'list',
    text,
    options: [],
    correct_answer: pool,
    minItems,
    ...(explanation ? { explanation } : {}),
  })
}

function explain(level, text, answer) {
  return base(level, {
    type: 'self_check',
    text,
    options: [],
    correct_answer: [answer],
  })
}

