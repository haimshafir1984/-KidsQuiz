const LEADER_COUNTRIES = LEADERS.map(([, country]) => country)

function leaderQuestion([leader, country], index) {
  const distractors = []
  let cursor = LEADER_COUNTRIES.indexOf(country)
  while (distractors.length < 3) {
    cursor = (cursor + 3 + (index % 2)) % LEADER_COUNTRIES.length
    const candidate = LEADER_COUNTRIES[cursor]
    if (candidate !== country && !distractors.includes(candidate)) distractors.push(candidate)
    else cursor += 1
  }
  const options = [...distractors]
  options.splice(index % 4, 0, country)
  return mc(L.matching, `${leader} - מנהיג של איזו מדינה או רשות?`, options, country)
}

